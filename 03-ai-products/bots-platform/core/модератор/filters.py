"""Фильтры: is_ad() и is_insult()."""
import re

# ---------------------------------------------------------------------------
# РЕКЛАМА
# ---------------------------------------------------------------------------

_TG_LINK   = re.compile(r"t\.me/[a-zA-Z0-9_+@]{3,}", re.I)
_EXT_LINK  = re.compile(r"https?://(?!t\.me)[^\s]{5,}", re.I)
_MENTION   = re.compile(r"@[a-zA-Z0-9_]{5,}")
_BARE_LINK = re.compile(r"\bwww\.[a-zA-Z0-9-]{2,}\.[a-zA-Z]{2,}", re.I)

_AD_WORDS  = re.compile(
    r"подпис(ывайся|ывайтесь|ка|ки|аться)"
    r"|перехо(ди|дите|дить)"
    r"|зарабат(ывай|ывайте|ок|ывать)"
    r"|пассивн\w+\s+доход"
    r"|сигнал(ы|ов|ьный\s+канал)"
    r"|инвест(ируй|иции|ируйте|ировать)"
    r"|крипт(о|овалют\w+)"
    r"|бесплатн\w+\s+(курс|доступ|обучен|гайд|урок)"
    r"|промокод|скидк[аиу]\b|партнёрск\w+|партнерск\w+"
    r"|реклам(а|ируем|ирую|ное\s+место)"
    r"|продаю\b|продам\b|куплю\b"
    r"|услуг[иа]\b.{0,30}(заказ|цена|стоим)"
    r"|пиш[иите]{1,2}\s+(в\s+)?(лс|лич[кн]|дм|директ)"
    r"|св[яя]жись|свяжитесь"
    r"|подробн\w+\s+(в\s+)?(лс|лич[кн]|профил)",
    re.I,
)

_PRICE     = re.compile(
    r"\d[\d\s]*(?:руб|₽|\$|usd|usdt)\b.{0,60}"
    r"(?:лс|лич[кн]|дм|вотсап|вацап|telegram|тг\b|контакт)",
    re.I,
)


def is_ad(text: str) -> bool:
    if _TG_LINK.search(text):
        return True
    if _MENTION.search(text):
        return True
    if _EXT_LINK.search(text):
        return True
    if _BARE_LINK.search(text):
        return True
    if _PRICE.search(text):
        return True
    return False


# ---------------------------------------------------------------------------
# ОСКОРБЛЕНИЯ И МАТ
#
# Структура: stem + \w* ловит все падежи/спряжения/суффиксы.
# Для корней, дающих ложные срабатывания (еб-), используем явные формы.
# ---------------------------------------------------------------------------

_INSULT_PATTERN = re.compile(
    # ===== ЛИЧНЫЕ ОСКОРБЛЕНИЯ =====
    # дурак — дурака, дураку, дураком, дуракам, дурацкий, дурачок...
    r"\bдура[кц]\w*\b|\bдуралей\w*\b|\bдурында\w*\b|\bдурашк\w+\b"
    # идиот — идиота, идиотка, идиотизм, идиотский...
    r"|\bидиот\w*\b"
    # тупой — тупого, тупица, тупак, тупоголовый...
    r"|\bтуп(ой|ую|ого|ому|ым|ая|ое|ых|ица|ицы|ице|ицу|ицей|ак\w*|оголов\w+)\b"
    # урод — урода, уродина, уродливый...
    r"|\bурод\w*\b"
    # дебил — дебила, дебилка, дебильный...
    r"|\bдебил\w*\b"
    # кретин — кретина, кретинизм, кретинский...
    r"|\bкретин\w*\b"
    # придурок — придурка, придурочный...
    r"|\bпридурок\w*\b|\bпридурочн\w+\b"
    # имбецил
    r"|\bимбецил\w*\b"
    # мразь — мрази, мразям...
    r"|\bмраз[ьиейям]\w*\b"
    # тварь — твари, тварям...
    r"|\bтвар[ьиейям]\w*\b"
    # сволочь — сволочи, сволочам...
    r"|\bсволоч[ьиейям]\w*\b"
    # подонок — подонка, подонков...
    r"|\bподонок\w*\b|\bподонк\w+\b"
    # негодяй — негодяя, негодяйка...
    r"|\bнегодяй\w*\b"
    # мерзавец — мерзавца, мерзавка...
    r"|\bмерзав\w+\b"
    # ублюдок — ублюдка, ублюдков...
    r"|\bублюдок\w*\b|\bублюдк\w+\b"
    # засранец — засранца, засранка...
    r"|\bзасран(ец|ка|цу|цем|цы|цев|цам)\b"
    # скотина — скотины, скотинам...
    r"|\bскотин\w+\b"
    # лох — лоха, лохов, лошара...
    r"|\bлох\w*\b|\bлошар\w+\b"
    # чмо, чмошник
    r"|\bчмо\b|\bчмошник\w*\b"
    # шалава, шлюха — все падежи
    r"|\bшалав\w+\b|\bшлюх\w*\b"
    # псих, психопат
    r"|\bпсих(опат\w*|ован\w+)\b"

    # ===== УГРОЗЫ =====
    r"|\bубью\b|\bубьёт[еь]?\b|\bприбью\b"
    r"|\bнайду.{1,20}(убью|прибью|разберусь)\b"

    # ===== МАТ =====

    # --- хуй: все падежи + производные с приставками ---
    # хуй, хуя, хую, хуем, хуе, хуи, хуёв
    r"|\bх[уy][йяеёию]\w*"
    # хуёвый, хуйня, хуйло и другие с согласной после корня
    r"|\bх[уy][её]\w+"
    r"|\bх[уy]й\w+"
    # приставочные: похуй, нахуй, захуярить, охуеть, схуяли, отхуячить...
    r"|\b(по|на|за|от|вы|при|у|до|пере|об|с)х[уy][йяеёию]\w*"
    r"|\bох[уy][еёи]\w*"

    # --- ёбать / еbать и все приставочные формы ---
    # Начало слова: ёбать, ёбаный, ёбнуть, ёблан, ёб
    r"|\b[её][бb](ать|ал[аи]?|ала?сь|аный|аная|аное|аных|аными"
    r"|нуть|нул[а]?|нёт|нёшь|лан[ауе]?|твою|ёт|ём|ёшь|ёте|ут|сь|ся|ись)?\b"
    # заёбать, наёбать, выёбываться, проёбать, отъёбать, доебать, переёбать
    r"|\b(за|на|вы|по|от|до|пере|при|об)ъ?[её][бb]\w*"
    # уёбок, уёбывать, уебать
    r"|\bу[её][бb]\w*"

    # --- пизда: все формы + приставочные ---
    # пизда, пизды, пизде, пизду, пиздой, пиздам, пиздах
    r"|\bп[иi]зд\w*"
    # спиздить, отпиздить, запиздячить, напиздеть, распиздяй...
    r"|\b(с|от|за|вы|на|до|пере|рас|за|у)п[иi]зд\w+"

    # --- блядь / блять: все формы ---
    # блядь, блять, бляди, блядей, блядям, блядями, блядях
    # блядский, блядун, блядина, блядовать, блядство
    r"|\bбля[дт]\w*"
    # заблядь, заблять и т.п.
    r"|\bза[бb]ля\w+"

    # --- мудак: все формы ---
    # мудак, мудака, мудаку, мудаком, мудаки, мудаков, мудакам
    # мудила, мудилы, мудиле, мудилу, мудилой
    # мудло, мудня, муде
    r"|\bмудак\w*\b|\bмудил\w+\b|\bмудл[оауе]\b|\bмудн[яе]\b"

    # --- сука / сучка: все падежи ---
    # сука, суки, суке, суку, сукой, сукам, суками
    r"|\bсук[ауиеойям]\w*\b"
    # сучка, сучки, сучке, сучку, сучкой, сучьё, сучья, сучьи
    r"|\bсуч[ькаиеёуой]\w*\b"

    # --- залупа: все падежи ---
    r"|\bзалуп\w+\b"

    # --- нахуй как отдельное слово (часто без пробела с предыдущим) ---
    r"|нах[уy][йяеёи]\w*",

    re.IGNORECASE | re.UNICODE,
)


def is_insult(text: str) -> bool:
    return bool(_INSULT_PATTERN.search(text))


